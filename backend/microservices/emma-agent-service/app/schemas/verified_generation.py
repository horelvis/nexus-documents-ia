class VerifiedDocumentRequest(BaseModel):
    """
    Request to generate a verified document.
    """
    query: str = Field(..., description="The generation query/prompt")
    tenant_id: str = Field(..., description="Tenant identifier for document isolation")
    session_id: Optional[str] = Field(
        default=None,
        description="Session ID for caching (auto-generated if not provided)"
    )
    user_id: Optional[str] = Field(None, description="User ID for audit")

    # Generation parameters
    max_claims: int = Field(
        default=20,
        ge=1,
        le=50,
        description="Maximum number of claims to generate"
    )
    claim_temperature: float = Field(
        default=0.3,
        ge=0.0,
        le=1.0,
        description="Temperature for claim generation (lower = more deterministic)"
    )

    # Verification parameters
    verification_timeout_seconds: int = Field(
        default=45,
        ge=10,
        le=120,
        description="Timeout per claim verification"
    )
    confidence_threshold: float = Field(
        default=0.7,
        ge=0.0,
        le=1.0,
        description="Minimum confidence to accept a claim"
    )
    auto_correct: bool = Field(
        default=True,
        description="Automatically accept suggested corrections"
    )
    max_correction_attempts: int = Field(
        default=2,
        ge=0,
        le=5,
        description="Max correction attempts per claim"
    )

    # Context parameters
    context_document_ids: List[str] = Field(
        default_factory=list,
        description="Specific indexed document IDs to use as context (Weaviate)"
    )
    uploaded_file_ids: List[str] = Field(
        default_factory=list,
        description="Uploaded (non-indexed) file IDs whose extracted text is used as context"
    )
    collections: List[str] = Field(
        default_factory=list,
        description="Weaviate collections to search for evidence"
    )

    class Config:
        json_schema_extra = {
            "example": {
                "query": "Genera un resumen del contrato con ACME incluyendo obligaciones y fechas clave",
                "tenant_id": "tenant-123",
                "max_claims": 10,
                "confidence_threshold": 0.75,
                "context_document_ids": ["doc-abc", "doc-def"]
            }
        }


class VerifiedClaimSummary(BaseModel):
    """Summary of a verified claim for the response."""
    text: str
    confidence: float
    status: VerificationStatus
    evidence_count: int


class VerifiedDocumentResponse(BaseModel):
    """
    Response containing the verified document.
    """
    session_id: str = Field(..., description="Session ID for this generation")
    query: str = Field(..., description="Original query")

    # The verified document
    document_text: str = Field(..., description="The assembled verified document")
    claims: List[VerifiedClaimSummary] = Field(
        default_factory=list,
        description="Summary of verified claims"
    )

    # Statistics
    total_claims_generated: int = Field(..., description="Total claims attempted")
    claims_verified: int = Field(..., description="Claims that passed verification")
    claims_corrected: int = Field(..., description="Claims that were corrected")
    claims_rejected: int = Field(..., description="Claims that were rejected")
    average_confidence: float = Field(..., ge=0.0, le=1.0)

    # Performance
    execution_time_ms: int = Field(..., description="Total execution time")
    verification_time_ms: int = Field(..., description="Time spent on verification")

    # Metadata
    evidence_document_ids: List[str] = Field(
        default_factory=list,
        description="All documents used as evidence"
    )
    created_at: datetime = Field(default_factory=datetime.utcnow)

    class Config:
        json_schema_extra = {
            "example": {
                "session_id": "session-xyz789",
                "query": "Genera un resumen del contrato con ACME",
                "document_text": "## Resumen del Contrato ACME\n\n1. El contrato establece...",
                "claims": [
                    {"text": "El contrato tiene vigencia de 2 años", "confidence": 0.92, "status": "verified", "evidence_count": 2}
                ],
                "total_claims_generated": 12,
                "claims_verified": 10,
                "claims_corrected": 1,
                "claims_rejected": 1,
                "average_confidence": 0.87,
                "execution_time_ms": 45000,
                "verification_time_ms": 38000
            }
        }


class VerificationSessionStatus(BaseModel):
    """
    Status of an ongoing or completed verification session.
    """
    session_id: str
    tenant_id: str
    status: str  # "in_progress", "completed", "error"
    claims_processed: int
    claims_total: int
    current_claim: Optional[str] = None
    progress_percent: int
    started_at: datetime
    updated_at: datetime
    error_message: Optional[str] = None


class SessionClaimsResponse(BaseModel):
    """Response containing verified claims for a session."""
    session_id: str
    tenant_id: str
    claims: List[VerifiedClaim]
    total_claims: int
    cache_ttl_remaining_seconds: Optional[int] = None
